核心方向不是單一「住工合一」。

包含：
- 企業錯峰上下班
- 友善彈性工時
- 捷運工程推進
- 電動小巴與最後一哩接駁
- 住宅及都市規劃

核心說法：

「內湖交通不能只靠再蓋一條路。真正要處理的是不同時間大量人口同時移動，以及最後一哩、工時和都市規劃一起造成的問題。」

